export function rdText(locale: Locale): Text {
  return locale === 'ar' ? ar : en;
}

/** Bytes in a short human form (bidi-isolated). */
export function bytes(n: number): string {
  if (n >= 1 << 30) return ltr(`${(n / (1 << 30)).toFixed(2)} GB`);
  if (n >= 1 << 20) return ltr(`${(n / (1 << 20)).toFixed(1)} MB`);
  if (n >= 1 << 10) return ltr(`${(n / (1 << 10)).toFixed(0)} KB`);
  return ltr(`${n} B`);
}
