export function policyText(locale: string): Text {
  return locale === 'ar' ? ar : en;
}

/** A profile's display name: built-ins in the reader's language, custom ones as typed. */
export function profileLabel(tx: Text, p: Pick<FleetPermissionProfile, 'builtin_key' | 'name'>): string {
  return p.builtin_key ? tx.builtin[p.builtin_key] : p.name;
}

/** The localized text of a refusal or other known API error code, or the server's own message. */
export function codeMessage(tx: Text, err: Pick<ApiError, 'code' | 'message'> | null | undefined): string | null {
  if (!err) return null;
  return tx.codes[err.code] ?? err.message;
}
