export const portsText = (locale: Locale): Dict => (locale === 'ar' ? ar : en);

/** "Plugged into Gi0/4 on Core switch" */
export function locationLine(loc: PortLocation, locale: Locale): string {
  const tx = portsText(locale);
  return `${tx.kind[loc.kind]} ${loc.port_name}${loc.port_alias ? ` (${loc.port_alias})` : ''} ${tx.on} ${loc.switch_name}`;
}
